"""Generate docs/RESULTS.md from the evaluation JSON files written by the training scripts (no hand-typed numbers)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVAL = ROOT / "ml" / "evaluation"
NAMES = {"breast_cancer": "Breast cancer (UCI WDBC)", "diabetes": "Diabetes (Pima Indians)", "heart_disease": "Heart disease (UCI Cleveland)"}
COLS = [("accuracy", "Accuracy"), ("precision", "Precision"), ("recall_sensitivity", "Recall"), ("specificity", "Specificity"),
        ("f1", "F1"), ("roc_auc", "ROC-AUC"), ("brier_score", "Brier"), ("ece_10bin", "ECE")]


def md_table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    lines = ["# Experimental results (generated)", "",
             "Generated by `python scripts/make_results_md.py` from `ml/evaluation/*_metrics.json`. All numbers come from executed "
             "training runs. Threshold 0.5 unless stated. Models are selected on the validation set; the test set is used once.", ""]
    for slug, title in NAMES.items():
        f = EVAL / f"{slug}_metrics.json"
        if not f.exists():
            lines += [f"## {title}", "", "_Not trained yet._", ""]
            continue
        m = json.loads(f.read_text())
        sel = m["selected_model"]
        dr = m.get("data_report")
        npos = m["test"][sel]["confusion_matrix"]["tp"] + m["test"][sel]["confusion_matrix"]["fn"]
        info = (f"- Rows: {dr['rows']}, features: {dr['features']}, positive fraction: {dr['positive_fraction']}" if dr
                else f"- Rows: {sum(m['split'].values())} (from split sizes)")
        lines += [f"## {title}", "", info,
                  f"- Split (train/val/test): {m['split']['train']}/{m['split']['val']}/{m['split']['test']}; positives in test set: {npos}",
                  f"- Selected on validation: **{sel}**", ""]
        rows = []
        for n, r in m["test"].items():
            cm = r["confusion_matrix"]
            rows.append([n + (" *" if n == sel else "")] + [f"{r[k]:.4f}" for k, _ in COLS] + [f"{cm['tn']}/{cm['fp']}/{cm['fn']}/{cm['tp']}"])
        lines += ["**Test set**", "", md_table(rows, ["Model"] + [h for _, h in COLS] + ["TN/FP/FN/TP"]), "", "\\* selected on validation data.", ""]
        if "repeated_cv_train_plus_val" in m:
            rows = [[n, f"{v['roc_auc']['mean']:.3f} ± {v['roc_auc']['std']:.3f}", f"{v['recall']['mean']:.3f} ± {v['recall']['std']:.3f}",
                     f"{v['specificity']['mean']:.3f} ± {v['specificity']['std']:.3f}"] for n, v in m["repeated_cv_train_plus_val"].items()]
            lines += ["**Repeated 5-fold CV on train+validation (3 repeats; test set untouched)**", "", md_table(rows, ["Model", "ROC-AUC", "Recall", "Specificity"]), ""]
        hs = m.get("high_sensitivity_operating_point")
        if hs:
            t = hs["test"]
            lines += [f"**High-sensitivity operating point** (threshold {hs['threshold']}, {hs['chosen_on']}): test recall {t['recall_sensitivity']:.3f}, "
                      f"specificity {t['specificity']:.3f}, confusion matrix {t['confusion_matrix']}.", ""]
        shap = EVAL / f"{slug}_shap_global.json"
        if shap.exists():
            s = json.loads(shap.read_text())
            top = list(s["mean_abs_shap"].items())[:5]
            lines += [f"**Top-5 SHAP features** ({s['unit']}): " + ", ".join(f"{k} ({v:.3f})" for k, v in top), ""]
    img = EVAL / "image_metrics.json"
    lines += ["## Image module", ""]
    if img.exists():
        m = json.loads(img.read_text())
        lines += [f"Dataset: {m['dataset']}; arch {m['arch']}; weights {m['weights']}; split {m['split']}.",
                  f"Test metrics: recall {m['test']['recall_sensitivity']:.3f}, specificity {m['test']['specificity']:.3f}, ROC-AUC {m['test']['roc_auc']:.3f}.", ""]
        if "synthetic" in m["dataset"].lower():
            lines += ["**These numbers come from a SYNTHETIC toy dataset and say nothing about medical performance.**", ""]
    else:
        lines += ["_No image model has been trained yet. See docs/IMAGE_MODULE.md. No image results are claimed._", ""]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
